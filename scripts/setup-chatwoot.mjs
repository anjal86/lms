#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';

function parseArgs(argv) {
  const result = {
    envPath: '.env.local',
    dockerEnvPath: 'docker/.env',
    baseUrl: '',
    token: '',
  };
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (value === '--env' && argv[index + 1]) result.envPath = argv[++index];
    else if (value === '--docker-env' && argv[index + 1]) result.dockerEnvPath = argv[++index];
    else if (value === '--url' && argv[index + 1]) result.baseUrl = argv[++index];
    else if (value === '--token' && argv[index + 1]) result.token = argv[++index];
    else if (value === '--help' || value === '-h') result.help = true;
  }
  return result;
}

function parseEnv(text) {
  const values = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator < 1) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

function envValue(value) {
  if (/^[A-Za-z0-9_./:@%+=,-]+$/.test(value)) return value;
  return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

function upsertEnv(text, key, value) {
  const lines = text ? text.split(/\r?\n/) : [];
  const expression = new RegExp(`^\\s*${key.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&')}\\s*=`);
  const replacement = `${key}=${envValue(value)}`;
  const index = lines.findIndex((line) => expression.test(line));
  if (index >= 0) {
    lines[index] = replacement;
    return lines.join('\n');
  }
  if (lines.length && lines.at(-1)?.trim()) lines.push('');
  lines.push(replacement);
  return lines.join('\n');
}

function isPlaceholder(value) {
  return !value || /replace-with|your-|placeholder|example/i.test(value);
}

function normalizeBaseUrl(value) {
  const url = new URL(value);
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error('Chatwoot URL must use http:// or https://.');
  url.pathname = url.pathname.replace(/\/$/, '');
  url.search = '';
  url.hash = '';
  return url.toString().replace(/\/$/, '');
}

function secureHex(bytes = 32) {
  return crypto.randomBytes(bytes).toString('hex');
}

function keepOrGenerate(values, key, bytes = 32) {
  const existing = values[key];
  return !isPlaceholder(existing) && existing.length >= 32 ? existing : secureHex(bytes);
}

function writeEnvFile(filePath, original, entries) {
  let next = original;
  if (!next.trim()) next = '# Local overrides generated by project setup scripts\n';
  for (const [key, value] of Object.entries(entries)) {
    if (value === undefined || value === null) continue;
    next = upsertEnv(next, key, String(value));
  }
  if (!next.endsWith('\n')) next += '\n';
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, next, { mode: 0o600 });
}

function printHelp() {
  console.log(`\nSelf-hosted Chatwoot Inbox setup\n\nUsage:\n  npm run setup:chatwoot\n  npm run setup:chatwoot -- --url http://localhost:3001\n  npm run setup:chatwoot -- --token YOUR_TOKEN\n\nOptions:\n  --env <path>         CRM environment file (default: .env.local)\n  --docker-env <path>  Docker Compose environment file (default: docker/.env)\n  --url <url>          Public Chatwoot Inbox URL\n  --token <token>      Chatwoot personal access token (optional on first boot)\n  -h, --help           Show this help\n`);
}

const args = parseArgs(process.argv.slice(2));
if (args.help) {
  printHelp();
  process.exit(0);
}

const envPath = path.resolve(process.cwd(), args.envPath);
const dockerEnvPath = path.resolve(process.cwd(), args.dockerEnvPath);
const original = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '';
const dockerOriginal = fs.existsSync(dockerEnvPath) ? fs.readFileSync(dockerEnvPath, 'utf8') : '';
const current = parseEnv(original);
const dockerCurrent = parseEnv(dockerOriginal);
const combined = { ...dockerCurrent, ...current };
const rl = readline.createInterface({ input, output });

console.log('\nSelf-hosted Chatwoot Inbox setup\n');
console.log(`CRM env:    ${path.relative(process.cwd(), envPath) || envPath}`);
console.log(`Docker env: ${path.relative(process.cwd(), dockerEnvPath) || dockerEnvPath}`);

try {
  const currentUrl = !isPlaceholder(combined.NEXT_PUBLIC_CHATWOOT_INBOX_URL)
    ? combined.NEXT_PUBLIC_CHATWOOT_INBOX_URL
    : !isPlaceholder(combined.CHATWOOT_PUBLIC_URL)
      ? combined.CHATWOOT_PUBLIC_URL
      : 'http://localhost:3001';
  const baseUrlAnswer = args.baseUrl || await rl.question(`Public Chatwoot Inbox URL [${currentUrl}]: `);
  const publicUrl = normalizeBaseUrl(baseUrlAnswer.trim() || currentUrl);

  let token = args.token.trim();
  if (!token && !isPlaceholder(combined.CHATWOOT_API_ACCESS_TOKEN)) {
    const replacement = await rl.question('Chatwoot API access token [press Enter to keep current token]: ');
    token = replacement.trim() || combined.CHATWOOT_API_ACCESS_TOKEN;
  }

  const integrationKey = /^[a-fA-F0-9]{64}$/.test(combined.INTEGRATION_TOKEN_ENCRYPTION_KEY || '')
    ? combined.INTEGRATION_TOKEN_ENCRYPTION_KEY
    : secureHex(32);

  const secrets = {
    CHATWOOT_POSTGRES_PASSWORD: keepOrGenerate(combined, 'CHATWOOT_POSTGRES_PASSWORD', 24),
    CHATWOOT_REDIS_PASSWORD: keepOrGenerate(combined, 'CHATWOOT_REDIS_PASSWORD', 24),
    CHATWOOT_SECRET_KEY_BASE: keepOrGenerate(combined, 'CHATWOOT_SECRET_KEY_BASE', 64),
    CHATWOOT_ACTIVE_RECORD_ENCRYPTION_PRIMARY_KEY: keepOrGenerate(combined, 'CHATWOOT_ACTIVE_RECORD_ENCRYPTION_PRIMARY_KEY', 32),
    CHATWOOT_ACTIVE_RECORD_ENCRYPTION_DETERMINISTIC_KEY: keepOrGenerate(combined, 'CHATWOOT_ACTIVE_RECORD_ENCRYPTION_DETERMINISTIC_KEY', 32),
    CHATWOOT_ACTIVE_RECORD_ENCRYPTION_KEY_DERIVATION_SALT: keepOrGenerate(combined, 'CHATWOOT_ACTIVE_RECORD_ENCRYPTION_KEY_DERIVATION_SALT', 32),
  };

  writeEnvFile(envPath, original, {
    CHATWOOT_BASE_URL: publicUrl,
    CHATWOOT_API_ACCESS_TOKEN: token || current.CHATWOOT_API_ACCESS_TOKEN || '',
    CHATWOOT_WEBHOOK_MAX_AGE_SECONDS: combined.CHATWOOT_WEBHOOK_MAX_AGE_SECONDS || '300',
    NEXT_PUBLIC_CHATWOOT_INBOX_URL: publicUrl,
    INTEGRATION_TOKEN_ENCRYPTION_KEY: integrationKey,
  });

  writeEnvFile(dockerEnvPath, dockerOriginal, {
    CHATWOOT_PUBLIC_URL: publicUrl,
    CHATWOOT_PORT: new URL(publicUrl).port || (publicUrl.startsWith('https://') ? '443' : '3001'),
    CHATWOOT_API_ACCESS_TOKEN: token || dockerCurrent.CHATWOOT_API_ACCESS_TOKEN || '',
    CHATWOOT_WEBHOOK_MAX_AGE_SECONDS: combined.CHATWOOT_WEBHOOK_MAX_AGE_SECONDS || '300',
    INTEGRATION_TOKEN_ENCRYPTION_KEY: integrationKey,
    ...secrets,
  });

  const appUrl = !isPlaceholder(combined.NEXT_PUBLIC_APP_URL)
    ? combined.NEXT_PUBLIC_APP_URL.replace(/\/$/, '')
    : 'http://localhost:3000';

  console.log('\n✓ Self-hosted Chatwoot configuration saved.');
  console.log(`✓ Inbox URL: ${publicUrl}`);
  console.log('✓ Dedicated Chatwoot Postgres/Redis/Rails encryption secrets are configured.');
  console.log('✓ CRM integration encryption key is configured.');
  console.log(token
    ? '✓ Chatwoot API access token configured.'
    : '! API token not set yet — this is expected on the first boot.');

  console.log('\nNext steps:');
  console.log('  1. Start Chatwoot: npm run chatwoot:up');
  console.log(`  2. First install only: open ${publicUrl}/installation/onboarding`);
  console.log('  3. Create the first Chatwoot administrator/account.');
  console.log('  4. Create a Chatwoot personal access token, then save it with:');
  console.log('     npm run setup:chatwoot -- --token YOUR_TOKEN');
  console.log('  5. Restart the CRM if it is already running: npm run dev');
  console.log(`  6. Open the CRM Inbox: ${appUrl}/inbox`);
  console.log(`  7. Configure CRM ↔ Chatwoot mapping at: ${appUrl}/inbox/channels/chatwoot\n`);
} catch (error) {
  console.error(`\n✗ ${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
} finally {
  rl.close();
}
