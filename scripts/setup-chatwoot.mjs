#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';

function parseArgs(argv) {
  const result = { envPath: '.env.local', baseUrl: '', token: '' };
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (value === '--env' && argv[index + 1]) result.envPath = argv[++index];
    else if (value === '--url' && argv[index + 1]) result.baseUrl = argv[++index];
    else if (value === '--token' && argv[index + 1]) result.token = argv[++index];
    else if (value === '--help' || value === '-h') result.help = true;
  }
  return result;
}

function parseEnv(text) {
  const values = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator < 1) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

function envValue(value) {
  if (/^[A-Za-z0-9_./:@%+=,-]+$/.test(value)) return value;
  return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

function upsertEnv(text, key, value) {
  const lines = text ? text.split(/\r?\n/) : [];
  const expression = new RegExp(`^\\s*${key.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&')}\\s*=`);
  const replacement = `${key}=${envValue(value)}`;
  const index = lines.findIndex((line) => expression.test(line));
  if (index >= 0) {
    lines[index] = replacement;
    return lines.join('\n');
  }
  if (lines.length && lines.at(-1)?.trim()) lines.push('');
  lines.push(replacement);
  return lines.join('\n');
}

function isPlaceholder(value) {
  return !value || /replace-with|your-|placeholder|example/i.test(value);
}

function normalizeBaseUrl(value) {
  const url = new URL(value);
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error('Chatwoot URL must use http:// or https://.');
  url.pathname = url.pathname.replace(/\/$/, '');
  url.search = '';
  url.hash = '';
  return url.toString().replace(/\/$/, '');
}

function printHelp() {
  console.log(`\nChatwoot local setup\n\nUsage:\n  npm run setup:chatwoot\n  npm run setup:chatwoot -- --url https://chat.example.com --token YOUR_TOKEN\n\nOptions:\n  --env <path>     Environment file to update (default: .env.local)\n  --url <url>      Chatwoot base URL\n  --token <token>  Chatwoot personal access token\n  -h, --help       Show this help\n`);
}

const args = parseArgs(process.argv.slice(2));
if (args.help) {
  printHelp();
  process.exit(0);
}

const envPath = path.resolve(process.cwd(), args.envPath);
const original = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '';
const current = parseEnv(original);
const rl = readline.createInterface({ input, output });

console.log('\nChatwoot CRM setup\n');
console.log(`Environment: ${path.relative(process.cwd(), envPath) || envPath}`);

try {
  const currentUrl = !isPlaceholder(current.CHATWOOT_BASE_URL)
    ? current.CHATWOOT_BASE_URL
    : 'http://localhost:3001';
  const baseUrlAnswer = args.baseUrl || await rl.question(`Chatwoot base URL [${currentUrl}]: `);
  const baseUrl = normalizeBaseUrl(baseUrlAnswer.trim() || currentUrl);

  let token = args.token.trim();
  if (!token) {
    if (!isPlaceholder(current.CHATWOOT_API_ACCESS_TOKEN)) {
      const replacement = await rl.question('Chatwoot API access token [press Enter to keep current token]: ');
      token = replacement.trim() || current.CHATWOOT_API_ACCESS_TOKEN;
    } else {
      token = (await rl.question('Chatwoot API access token: ')).trim();
    }
  }
  if (!token || isPlaceholder(token)) throw new Error('A real Chatwoot API access token is required.');

  let encryptionKey = current.INTEGRATION_TOKEN_ENCRYPTION_KEY;
  let generatedEncryptionKey = false;
  if (isPlaceholder(encryptionKey) || !/^[a-fA-F0-9]{64}$/.test(encryptionKey || '')) {
    encryptionKey = crypto.randomBytes(32).toString('hex');
    generatedEncryptionKey = true;
  }

  const appUrl = !isPlaceholder(current.NEXT_PUBLIC_APP_URL)
    ? current.NEXT_PUBLIC_APP_URL.replace(/\/$/, '')
    : 'http://localhost:3000';

  let next = original;
  if (!next.trim()) next = '# Local overrides generated by project setup scripts\n';
  next = upsertEnv(next, 'CHATWOOT_BASE_URL', baseUrl);
  next = upsertEnv(next, 'CHATWOOT_API_ACCESS_TOKEN', token);
  next = upsertEnv(next, 'CHATWOOT_WEBHOOK_MAX_AGE_SECONDS', current.CHATWOOT_WEBHOOK_MAX_AGE_SECONDS || '300');
  next = upsertEnv(next, 'INTEGRATION_TOKEN_ENCRYPTION_KEY', encryptionKey);
  if (!next.endsWith('\n')) next += '\n';

  fs.mkdirSync(path.dirname(envPath), { recursive: true });
  fs.writeFileSync(envPath, next, { mode: 0o600 });

  console.log('\n✓ Chatwoot server configuration saved.');
  console.log(`✓ CHATWOOT_BASE_URL = ${baseUrl}`);
  console.log('✓ CHATWOOT_API_ACCESS_TOKEN = configured (hidden)');
  console.log(`✓ Webhook replay window = ${current.CHATWOOT_WEBHOOK_MAX_AGE_SECONDS || '300'} seconds`);
  console.log(generatedEncryptionKey
    ? '✓ Generated INTEGRATION_TOKEN_ENCRYPTION_KEY for encrypted workspace secrets.'
    : '✓ Existing INTEGRATION_TOKEN_ENCRYPTION_KEY preserved.');

  console.log('\nNext steps:');
  console.log('  1. Restart the CRM: npm run dev');
  console.log(`  2. Open: ${appUrl}/inbox/channels/chatwoot`);
  console.log('  3. Enter the Chatwoot Account ID and webhook signing secret, then click Verify & save.');
  console.log('  4. In Chatwoot, configure the workspace webhook to:');
  console.log(`     ${appUrl}/api/integrations/webhooks/chatwoot`);
  console.log('  5. Back in the CRM, click Discover inboxes.\n');
} catch (error) {
  console.error(`\n✗ ${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
} finally {
  rl.close();
}
